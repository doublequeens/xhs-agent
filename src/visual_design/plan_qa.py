"""Deterministic design-plan QA (Task 9).

Pure rules — no LLM, no network, no clock, no randomness. ``evaluate_design_plan``
hard-gates a ``CarouselDesignPlan`` against its source atoms / direction /
asset manifest / family profile and returns a ``DesignPlanQAResult`` with
actionable, deterministically-ordered issues. The reviser loop (Task 8) and the
route defined here consume the result; graph wiring is Task 14.

Rule prefixes are ``content.`` / ``family.`` / ``asset.`` / ``geometry.`` /
``typography.``; the three attestations key off ``content.`` / ``family.`` /
``asset.``.
"""

